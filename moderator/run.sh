#!/bin/bash
# launchd wrapper for the moderator's night (com.chalant.promptocracy-moderator.<slug>, one job per game, twice a night: the main run just after the day's end, which stays for the whole night, and a backstop an hour before the deadline; the schedule is generated by schedule.mjs). Reads ONLY the keys
# the runner needs from ~/chalantbot/.env (never prints them) and runs one pass per game in games.manifest.json.
# The model never sees these: process-day.mjs gives `claude -p` a scrubbed environment (PATH, HOME, USER, LANG,
# TMPDIR, and the subscription OAuth token claude itself needs).
set -u
export PATH="$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin"
ENV_FILE="$HOME/chalantbot/.env"
HERE="$(cd "$(dirname "$0")" && pwd)"
get() { grep -E "^$1=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- | sed -e 's/^["'"'"']//' -e 's/["'"'"']$//'; }
[ -f "$ENV_FILE" ] || { echo "moderator: no $ENV_FILE" >&2; exit 2; }
# The subscription credential only (sk-ant-oat01-...), never an API key: plan usage, not API dollars.
oat="$(get CLAUDE_API_KEY)"
case "$oat" in sk-ant-oat01-*) export CLAUDE_CODE_OAUTH_TOKEN="$oat" ;; *) echo "moderator: CLAUDE_API_KEY is not an oat01 subscription token; refusing to run" >&2; exit 2 ;; esac
unset ANTHROPIC_API_KEY
for k in CLOUDFLARE_WORKERS_TOKEN CLOUDFLARE_ACCOUNT_ID PROMPTOCRACY_BUILD_TRIGGER PROMPTOCRACY_API; do v="$(get "$k")"; [ -n "$v" ] && export "$k=$v"; done
status=0
# ONE game per launchd job (com.chalant.promptocracy-moderator.<slug>, generated by schedule.mjs): launchd does not start a job
# that is still running, so a game's hours-long main run must not share a job with another game's starts.
SLUG="${1:?usage: run.sh <game slug>}"
key="PROMPTOCRACY_MODERATOR_TOKEN_$(echo "$SLUG" | tr '[:lower:]-' '[:upper:]_')"
v="$(get "$key")"
[ -n "$v" ] || { echo "moderator: no $key in $ENV_FILE: $SLUG is not moderated from this machine" >&2; exit 2; }
export "$key=$v"
/opt/homebrew/bin/node "$HERE/process-day.mjs" --slug "$SLUG" || status=1
# A night that was claimed or re-tagged left a flag: the game's time zone may have changed, so regenerate the register and
# the schedules now, after this run (a reload of the job must not cut it short). It reloads only the jobs whose schedule
# changed. A failure leaves the old schedule in place and the flag is put back for the next run.
STATE_DIR="${MODERATOR_STATE_DIR:-$HOME/chalantbot/logs/promptocracy-moderator}"
if [ -f "$STATE_DIR/reschedule.flag" ]; then
  rm -f "$STATE_DIR/reschedule.flag"
  /opt/homebrew/bin/node "$HERE/schedule.mjs" || { status=1; touch "$STATE_DIR/reschedule.flag"; }
fi
exit $status
